#!/usr/bin/env python3
"""Evaluate reviewed datasets/subsets and measure batch-one inference latency."""

import argparse
from pathlib import Path
import time

import numpy as np

try:
    from .common import check_model_names, new_output, sha256, snapshot, write_json
    from .dataset import images_in, inspect_dataset
except ImportError:
    from common import check_model_names, new_output, sha256, snapshot, write_json
    from dataset import images_in, inspect_dataset


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--weights', required=True)
    parser.add_argument('--data', required=True)
    parser.add_argument('--split', choices=['train', 'val', 'test'], default='test')
    parser.add_argument('--subset', help='explicit tag generated by group split tool')
    parser.add_argument('--output', required=True)
    parser.add_argument('--imgsz', type=int, default=640)
    parser.add_argument('--device', default='0')
    parser.add_argument('--conf', type=float, default=0.25, help='sample prediction threshold')
    parser.add_argument('--samples', type=int, default=20)
    args = parser.parse_args()
    from ultralytics import YOLO
    import torch
    data, manifest = inspect_dataset(args.data, require_review=True)
    paths = [Path(e['image']) for e in manifest['entries'] if e['split'] == args.split]
    if args.subset:
        if Path(args.subset).name != args.subset:
            raise ValueError('subset must be a tag name')
        subset = Path(data['path']) / 'subsets' / f'{args.split}_{args.subset}.txt'
        paths = images_in(subset)
        allowed = {e['image'] for e in manifest['entries'] if e['split'] == args.split}
        if not paths or not all(str(p) in allowed for p in paths):
            raise ValueError('Subset must contain only images from the requested reviewed split')
        data[args.split] = str(subset)
    model = YOLO(args.weights, task='detect')
    check_model_names(model, data['names'])
    output = new_output(args.output)
    snapshot(output, vars(args), data, manifest)
    val = model.val(data=str(output / 'data.yaml'), split=args.split, imgsz=args.imgsz,
                    device=args.device, batch=1, plots=True, project=str(output),
                    name='validation', exist_ok=True, workers=0)
    # Warm up separately; synchronize CUDA to make wall timings meaningful.
    predict = dict(imgsz=args.imgsz, device=args.device, conf=args.conf, verbose=False)
    model.predict(str(paths[0]), **predict)
    latencies, timings = [], []
    sample_dir = output / 'samples'
    sample_dir.mkdir()
    use_cuda = str(args.device).lower() != 'cpu' and torch.cuda.is_available()
    for i, path in enumerate(paths):
        if use_cuda:
            torch.cuda.synchronize()
        start = time.perf_counter()
        result = model.predict(str(path), **predict)[0]
        if use_cuda:
            torch.cuda.synchronize()
        ms = (time.perf_counter()-start)*1000
        latencies.append(ms)
        timings.append(dict(image=str(path), wall_ms=ms, ultralytics_ms=result.speed))
        if i < args.samples:
            result.save(filename=str(sample_dir / f'{i:05d}_{path.stem}.jpg'))
    write_json(output / 'image_timings.json', timings)
    write_json(output / 'metrics.json', dict(
        weights_sha256=sha256(args.weights), names=data['names'], split=args.split,
        subset=args.subset, images=len(paths), dataset_fingerprint=manifest['fingerprint'],
        precision=float(val.box.mp), recall=float(val.box.mr), map50=float(val.box.map50),
        map50_95=float(val.box.map), validation_speed_ms=val.speed,
        batch1_wall_ms=dict(mean=float(np.mean(latencies)), p50=float(np.median(latencies)),
                            p95=float(np.percentile(latencies, 95))),
        timing_scope='batch=1, includes image loading/preprocess/NMS, excludes warmup; '
                     'not ROS end-to-end latency',
        temporal_missed_detection_metrics='NOT VERIFIED: requires reviewed video timeline'))
    print((output / 'metrics.json').read_text())


if __name__ == '__main__':
    main()
